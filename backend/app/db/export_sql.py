"""Render database/schema.sql (tables + seed data) WITHOUT connecting to any database.

    python -m backend.app.db.export_sql

Useful for running the schema by hand in pgAdmin's Query Tool.
"""
import io
import json
from contextlib import redirect_stdout

from alembic import command
from alembic.config import Config

from backend.app.core.config import PROJECT_ROOT
from backend.app.db.seed import BEHAVIORAL, ROLES

OUT = PROJECT_ROOT / "database" / "schema.sql"


def _q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _j(value) -> str:
    return _q(json.dumps(value)) + "::jsonb"


def schema_sql() -> str:
    cfg = Config(str(PROJECT_ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(PROJECT_ROOT / "backend/app/db/migrations"))
    buf = io.StringIO()
    with redirect_stdout(buf):
        command.upgrade(cfg, "head", sql=True)
    return buf.getvalue()


def seed_sql() -> str:
    lines = ["-- Seed data (same as backend/app/db/seed.py)", "BEGIN;"]
    for role in ROLES:
        lines.append(
            "INSERT INTO job_roles (title, description, required_skills) VALUES "
            f"({_q(role['title'])}, {_q(role['description'])}, {_j(role['required_skills'])});"
        )
        all_q = BEHAVIORAL[:1] + role["questions"] + BEHAVIORAL[1:]
        for i, q in enumerate(all_q):
            lines.append(
                "INSERT INTO questions (role_id, order_index, text, ideal_answer, keywords, category, "
                "time_limit_sec) VALUES ("
                f"(SELECT id FROM job_roles WHERE title = {_q(role['title'])}), {i}, {_q(q['text'])}, "
                f"{_q(q['ideal_answer'])}, {_j(q['keywords'])}, {_q(q.get('category', 'technical'))}, "
                f"{q.get('time_limit_sec', 120)});"
            )
    lines.append("COMMIT;")
    return "\n".join(lines) + "\n"


def main() -> None:
    header = (
        "-- AI Interview Analyzer - PostgreSQL schema + seed data\n"
        "-- GENERATED by `python -m backend.app.db.export_sql`. Do not edit by hand.\n"
        "-- Usage: pgAdmin > interview_ai database > Query Tool > open this file > Run (F5).\n"
        "-- Easier alternative: `python -m backend.app.db.setup` (does the same automatically).\n\n"
    )
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(header + schema_sql() + "\n" + seed_sql(), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
